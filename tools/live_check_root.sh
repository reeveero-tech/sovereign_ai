#!/usr/bin/env bash
# R-814b/c — فحص جذر المنشور: 200 مضمون من المنادي؛ هنا: غير فارغ وبلا كلمة المالك الممنوعة.
# سكربت مستقل يختبره pytest على عينات موجبة وسالبة (درس أول تشغيل: rg غائبة عن
# مشغلات GitHub و«فشل الأداة» داخل if ظهر نجاحًا كاذبًا — درس المراجعة التاسعة:
# فشل grep نفسه (رمز >1) ليس «نظيفًا» — يُعلن خلل فحص لا نجاحًا).
# رموز الخروج: 0 سليم، 1 عيب (كلمة ممنوعة/صفحة فارغة)، 2 خلل فحص (ليس نجاحًا أبدًا).
FILE="${1:?المطلوب مسار ملف الصفحة}"
[ -s "$FILE" ] || { echo "::error::الصفحة فارغة — لا يُفحص فراغ"; exit 1; }
set +e
grep -q "سيادي" "$FILE"
RC=$?
set -e
case "$RC" in
  0) echo "::error::الصفحة الرئيسية تحوي كلمة ممنوعة بأمر المالك (البند ٧)"; exit 1;;
  1) echo "OK root page (nonempty, no forbidden word)"; exit 0;;
  *) echo "::error::خلل فحص: grep رد $RC — فشل الفحص ليس نجاحًا أبدًا"; exit 2;;
esac
